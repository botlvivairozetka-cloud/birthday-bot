"""
Конфігурація бота. Усі значення читаються ЗІ ЗМІННИХ СЕРЕДОВИЩА, без жодних
реальних ID чи токенів прямо в коді — це принципово важливо, бо репозиторій
публічний. Реальні значення задаються через GitHub Secrets / Variables
(див. README.md, Крок 4) і НІКОЛИ не потрапляють у сам код.

Якщо якесь обов'язкове значення не задане — скрипт одразу впаде з
зрозумілою помилкою (а не мовчки піде в чужу тестову групу за замовчуванням).
"""
import os
from dotenv import load_dotenv

load_dotenv()


def _required(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(
            f"Не задано обов'язкову змінну середовища {name}. "
            f"Перевірте GitHub Secrets/Variables (або .env для локального тесту)."
        )
    return value


def _required_int(name: str) -> int:
    return int(_required(name))


# --- Telegram ---
BOT_TOKEN = _required("BOT_TOKEN")

# Група/гілка, куди йдуть ВІТАННЯ
TARGET_CHAT_ID = _required_int("TARGET_CHAT_ID")
TARGET_TOPIC_ID = _required_int("TARGET_TOPIC_ID")

# Група/гілка, куди йдуть СИСТЕМНІ ЛОГИ
LOG_CHAT_ID = _required_int("LOG_CHAT_ID")
LOG_TOPIC_ID = _required_int("LOG_TOPIC_ID")

# --- Google Sheets ---
GOOGLE_SHEET_ID = _required("GOOGLE_SHEET_ID")
GOOGLE_SHEET_TAB = os.getenv("GOOGLE_SHEET_TAB", "Аркуш1")
GOOGLE_CREDENTIALS_FILE = os.getenv("GOOGLE_CREDENTIALS_FILE", "credentials.json")

# Назва ОКРЕМОГО службового аркуша (вкладки), де бот зберігає весь свій
# технічний стан — HR його ніколи не редагує і навіть не бачить у
# звичайній роботі з даними працівників. Якщо аркуша з такою назвою ще
# немає в таблиці — бот створює його сам автоматично при першому запуску.
BOT_STATE_SHEET_TAB = os.getenv("BOT_STATE_SHEET_TAB", "BotState")

# Колонки в ОСНОВНОМУ таблиці, які заповнює HR (1 = A, 2 = B, ...)
COL_NUM = 1          # № в группе
COL_NAME = 2         # Физическое лицо
COL_BIRTHDATE = 3    # Дата рождения

# --- Розклад ---
# Бот працює як постійний фоновий процес (Render), сам себе перевіряє
# кожні кілька хвилин.
TIMEZONE = os.getenv("TIMEZONE", "Europe/Kyiv")

# Вікно, коли бот МОЖЕ фактично надсилати привітання (за годинами Києва,
# 24-годинний формат). Поза цим вікном бот усе одно перевіряє таблицю,
# пише ранкове зведення в логи тощо — просто НЕ надсилає сам текст
# привітання, аж поки не настане SEND_WINDOW_START_HOUR.
SEND_WINDOW_START_HOUR = int(os.getenv("SEND_WINDOW_START_HOUR", "10"))
SEND_WINDOW_END_HOUR = int(os.getenv("SEND_WINDOW_END_HOUR", "20"))

# Рядок на службовому аркуші (BOT_STATE_SHEET_TAB), де живуть самі дані
# стану. Рядок 1 того аркуша лишається під людські підписи-заголовки
# (див. sheets_client._init_state_sheet), щоб будь-хто, хто випадково
# туди зазирне, одразу зрозумів призначення кожної колонки.
STATE_ROW = 2

# Колонки на службовому аркуші, де бот зберігає стан (щоб пам'ятати
# "сьогодні вже писав зведення" / "сьогодні вже чистив стан" між
# окремими циклами перевірки). Це єдине місце, куди бот щось пише —
# і воно повністю відокремлене від основного аркуша з працівниками.
