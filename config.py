STATE_CELL_SENT_KEYS = 4      # D — список "кому вже відправлено сьогодні"
                               #     за ключем Ім'я+Дата+Підрозділ (НЕ за
                               #     номером рядка — це і захищає від
                               #     збоїв, якщо HR перевставить дані)
STATE_CELL_DUP_WARNING = 5    # E — дата останнього попередження про
                               #     колізію ключів (щоб не дублювати
                               #     попередження в логах щоцикл)
STATE_CELL_SEEN_KEYS = 6      # F — список УСІХ сьогоднішніх іменинників,
                               #     яких бот уже "бачив" у таблиці (не
                               #     плутати з "кому відправлено" — цей
                               #     список потрібен окремо, щоб
                               #     детектувати нових людей, яких HR
                               #     додав У ТАБЛИЦЮ вже ПІСЛЯ ранкового
                               #     зведення, і повідомити про це в логи)
STATE_CELL_TEMPLATE_HISTORY = 7   # G — історія використаних шаблонів
