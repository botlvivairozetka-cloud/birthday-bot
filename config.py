                               #     (включно з одним днем) не повторювались
STATE_CELL_INTRO_HISTORY = 8      # H — історія використаних ВСТУПНИХ фраз
                               #     (тільки для першого привітання за
                               #     день) за останні 31 день, щоб жоден
                               #     вступ не повторювався протягом
                               #     цілого місяця

# Скільки днів "пам'ятати" історію використаних шаблонів, щоб не
# повторюватись. Вимога: жодне привітання за тиждень не повинно
# збігатись з іншим — тому 7.
TEMPLATE_HISTORY_DAYS = 7

# Скільки днів "пам'ятати" історію використаних вступних фраз. Вимога:
